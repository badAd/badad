<h4 id="hits">What are hits and how are they calculated?</h4>
<p>
	"Hits" are counted each time a Partner website makes a "request" to embed ads via the embed code.
	The number of hits for the current hit cycle are displayed in the Partner area next to a domain are "current" and have not
	yet been tallied for payout. Once hits have been tallied for payout, the totals are counted in the Site History and are reset
	for the current hit cycle.
</p>
<p>
	The Partner Center page also displays the total hits and the percentage of the Partner's contribution to all ads from all Partners.
</p>

<h4 id="meaning">What are "Ad Views", "badAd Views", and "Ad Clicks"</h4>
<p>
	These refer to different factors in calculating the hit count of ads viewed on a Partner site.
</p>
<ul>
	<li><b>"Ad Views"</b>: The number of ads viewed, one visit countint the number of "Ads to Show" viewed in your settings per domain</li>
	<li><b>"badAd Views"</b>: The times the "$siteTitle" link at the top of embedded ads has been viewed. This is also counted in your total hit count.</li>
	<li><b>"Ad Clicks"</b>: The number of times an ad "Contact" link or the "$siteTitle" link has been clicked. Each counts five times that of a single ad view in determining the total hit calculation.</li>
</ul>
<p>
	Each time a visitor loads the web page with embedded ads, it will count as one "badAd View" plus however many "Ads to Show" you have selected in your setting. For example, if you have "Ads to Show"
	set at 6, the total ads counted for that visit will be 7, which includes the "badAd View" (the '$siteTitle') link at the top. If someone clicks on the "Contact" link or the "$siteTitle" link,
	it will be counted so that you will get credit, which counts five times as much as a normal "Ad View" or "badAd View" in the grand total of your total share count for revenue.
</p>

<h4 id="zero">"Ads to Show" at zero only lists <b>badad.one</b>, 5 share counts per click</h4>
<p>
	Setting "Ads to Show" to "zero (0)" will render only the <b>badad.one</b> link in your site project,
	and you receive 5 share counts when a visitor clicks on it, just as if someone clicks on any ad.
</p>

